"""Monokernel shape code generator.

Single source of truth: ``csrc/moe/moe_monokernel/shapes.json``.  The kernel is
template-specialized on (N, K, E) at compile time, so every distinct shape needs
its own ``Dims`` instantiation + op symbol + bindings + dispatch + tuner entry.
Hand-maintaining those across files is error-prone; this script emits them all
from the one table.

Outputs (written under ``csrc/moe/moe_monokernel/generated/``) — each is an
``#include`` / ``import`` consumed by a hand-written source, so regeneration
never rewrites hand code:

  dims_generated.inc       — Dims_* structs (+ legacy `using` aliases)
  wrapper_generated.inc    — MOEMONOKERNEL_TOPK_WRAPPER_IMPLEMENTATION,
                             MONO_CONFIGS_* X-macro tables, dispatch_tunable_*,
                             *_tunable_impl bodies
  ops_generated.inc        — op + tunable-op forward declarations
  defs_generated.inc       — torch m.def schemas (stable-ABI fragment)
  impls_generated.inc      — torch m.impl registrations (full-libtorch
                             TORCH_LIBRARY_IMPL in moe_wrapper.cu)
  monokernel_shapes.py     — Python dispatch table (E,N,K)->op names + raw-upproj
                             config-id sets + tuner SHAPE / MODELS metadata

Naming: shape-keyed ``E{E}_N{N}_K{K}`` is canonical; a shape's ``legacy_cpp_name``
(e.g. ``Qwen3_5_35B``) gets a C++ ``using`` alias and the legacy op symbols so
existing callers keep working.

Usage:
  gen_shapes.py                 # regenerate all outputs
  gen_shapes.py --check         # exit 1 if outputs are stale (CI guard)
  gen_shapes.py --print dims    # print one section to stdout (debug)
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))  # repo root
MONO = os.path.normpath(os.path.join(HERE, ".."))  # moe_monokernel/
SHAPES_JSON = os.path.join(MONO, "shapes.json")
GEN_DIR = os.path.join(MONO, "generated")  # C++ .inc files (#included by sources)
# The Python registry must be importable from the installed `vllm` package
# (serving + tuner run outside the repo root), so it lands next to the other
# fused_moe Python helpers rather than under csrc/.
PY_PKG_DIR = os.path.join(ROOT, "vllm", "model_executor", "layers", "fused_moe")
ATOM = 128
WGMMA_K = 128

GEN_HEADER = (
    "// @generated by csrc/moe/moe_monokernel/tools/gen_shapes.py from\n"
    "// csrc/moe/moe_monokernel/shapes.json — DO NOT EDIT BY HAND.\n"
    "// Re-run gen_shapes.py after editing shapes.json.\n\n"
)
PY_GEN_HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# SPDX-FileCopyrightText: Copyright contributors to the vLLM project\n"
    "# @generated by csrc/moe/moe_monokernel/tools/gen_shapes.py from\n"
    "# csrc/moe/moe_monokernel/shapes.json — DO NOT EDIT BY HAND.\n\n"
)


def cpp_name(shape):
    """Canonical shape-keyed C++ Dims/op infix: E{E}_N{N}_K{K}."""
    return f"E{shape['E']}_N{shape['N']}_K{shape['K']}"


def legacy_infix(shape):
    """Legacy op/Dims infix (e.g. E256_Qwen3_5_35B) or None.  Kept as a
    back-compat alias so existing Python/test callers that reference the old
    symbol names keep working after the switch to shape-keyed canonical names."""
    lc = shape.get("legacy_cpp_name")
    return f"E{shape['E']}_{lc}" if lc else None


def uch_of(shape, dct, cfg=None):
    """UP_COL_HALVES for a shape/config.

    DECOUPLED shapes pin an explicit `up_col_halves` (the up/down grids are
    chosen independently, so UCH does not follow the DCT coupling identity);
    return it verbatim.  Individual configs may also set `uch` to test a
    decoupled/raw carve without making the whole shape raw.  Otherwise,
    COUPLED shapes derive UCH = max(1, 2*N*DCT/(128*K)), mirroring the C++
    `up_col_halves<Dims>` fallback.  `dct` is per-config so a coupled shape
    with mixed DCT (e.g. 35B cfg4/5 at DCT=512) reports the right UCH per
    config."""
    if cfg is not None and cfg.get("uch") is not None:
        return int(cfg["uch"])
    if shape.get("up_col_halves") is not None:
        return int(shape["up_col_halves"])
    v = (2 * shape["N"] * dct) // (ATOM * shape["K"])
    return v if v > 0 else 1


def load_shapes():
    with open(SHAPES_JSON) as f:
        data = json.load(f)
    shapes = data["shapes"]
    # Validate constraints early — a bad shape should fail here, not at nvcc.
    seen_keys, seen_enk = set(), set()
    for s in shapes:
        E, N, K = s["E"], s["N"], s["K"]
        assert E % 32 == 0, f"{s['key']}: E={E} must be a multiple of 32"
        assert N % ATOM == 0, f"{s['key']}: N={N} must be a multiple of 128"
        assert K % ATOM == 0, f"{s['key']}: K={K} must be a multiple of 128"
        assert s["default_top_k"] <= 8, f"{s['key']}: default_top_k must be <= 8"
        assert s["configs"], f"{s['key']}: needs at least config 0"
        assert s["configs"][0]["id"] == 0, f"{s['key']}: config 0 must be the default"
        ids = [c["id"] for c in s["configs"]]
        assert ids == sorted(set(ids)), f"{s['key']}: config ids must be unique/sorted"
        assert s["key"] not in seen_keys, f"duplicate shape key {s['key']}"
        seen_keys.add(s["key"])
        enk = (E, N, K)
        assert enk not in seen_enk, f"duplicate (E,N,K)={enk}"
        seen_enk.add(enk)
    return data


