def config_is_raw_upproj(E, N_fused, K, config_id):
    """True if the selected config uses the raw two-TMA up-proj (UCH>=2) and
    therefore must NOT be fed Python-interleaved weights.  Shape-agnostic:
    derived from the registry's per-shape raw-config-id set."""
    if config_id is None or config_id < 0:
        return False
    r = BY_ENK.get((E, N_fused, K))
    if r is None:
        return False
    return r["all_raw"] or (config_id in set(r["raw_upproj_config_ids"]))


def resolve_config_id(E, N_fused, K, env_value):
    """Parse a MONOKERNEL_CONFIG env string into a config id for this shape.
    Forms: bare int (any shape) | name:id (35b/122b/...) | E{E}N{N}K{K}:id
    (N here is N_fused).  Returns -1 (shipped default) if unset/unmatched."""
    raw = (env_value or "").strip()
    if not raw:
        return -1
    if raw.lstrip("-").isdigit():
        return int(raw)
    r = BY_ENK.get((E, N_fused, K))
    names = set()
    if r is not None:
        names = {r["key"].lower(), *[a.lower() for a in r["aliases"]]}
    enk_key = f"e{E}n{N_fused}k{K}"
    for part in raw.split(","):
        if ":" not in part:
            continue
        key, _, val = part.partition(":")
        key = key.strip().lower()
        if (key in names or key == enk_key) and val.strip().lstrip("-").isdigit():
            return int(val.strip())
    return -1
