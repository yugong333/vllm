def out_dir_for(fn):
    """C++ .inc files live under generated/; the Python registry must be
    importable from the installed vllm package, so it lands in PY_PKG_DIR."""
    return PY_PKG_DIR if fn.endswith(".py") else GEN_DIR


def render(data):
    shapes = data["shapes"]
    rendered = {}
    for fn, (_kind, emitter) in OUTPUTS.items():
        rendered[fn] = emitter(data) if emitter is emit_python else emitter(shapes)
    return rendered


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if any generated file is stale (CI guard)",
    )
    ap.add_argument(
        "--print",
        dest="section",
        choices=["dims", "config_table", "wrapper", "ops", "defs", "impls", "python"],
        help="print one section to stdout and exit (no files written)",
    )
    args = ap.parse_args()

    data = load_shapes()

    if args.section:
        key = {"python": "monokernel_shapes.py"}.get(
            args.section, f"{args.section}_generated.inc"
        )
        print(render(data)[key])
        return

    os.makedirs(GEN_DIR, exist_ok=True)
    rendered = render(data)
    stale = []
    for fn, content in rendered.items():
        path = os.path.join(out_dir_for(fn), fn)
        if os.path.exists(path):
            with open(path) as f:
                old = f.read()
        else:
            old = None
        if old != content:
            stale.append(fn)
            if not args.check:
                with open(path, "w") as f:
                    f.write(content)
    if args.check:
        if stale:
            print(
                f"STALE generated files (re-run gen_shapes.py): {stale}",
                file=sys.stderr,
            )
            sys.exit(1)
        print("generated files up to date")
    else:
        for fn in rendered:
            print(f"  {os.path.relpath(os.path.join(out_dir_for(fn), fn), ROOT)}")
        print(f"wrote {len(rendered)} files ({len(stale)} changed: {stale or 'none'})")
        print(f"shapes: {[s['key'] for s in data['shapes']]}")


if __name__ == "__main__":
    main()
